// Runs the typegen command the way docs/rules/typings.md documents it, against the mock server.

import { execFile } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";
import { build } from "esbuild";
import { MockHomeAssistant } from "@home-engine/engine/testing";
import { afterAll, beforeAll, describe, expect, it } from "vitest";

const run = promisify(execFile);
const TOKEN = "typegen-cli-token";

describe("home-engine-typegen command", () => {
  let ha: MockHomeAssistant;
  let dir: string;
  let cli: string;

  beforeAll(async () => {
    const cache = fileURLToPath(new URL("../node_modules/.cache", import.meta.url));
    mkdirSync(cache, { recursive: true });
    dir = mkdtempSync(join(cache, "typegen-cli-"));
    cli = join(dir, "cli.mjs");
    await build({
      entryPoints: [fileURLToPath(new URL("./cli.ts", import.meta.url))],
      outfile: cli,
      bundle: true,
      platform: "node",
      format: "esm",
      packages: "external",
      logLevel: "silent",
    });
    ha = new MockHomeAssistant({ tokens: [TOKEN] });
    ha.setState("light.kitchen", "on");
    await ha.start();
  });

  afterAll(async () => {
    await ha.stop();
    rmSync(dir, { recursive: true, force: true });
  });

  const typegen = (args: string[], env: Record<string, string>) =>
    run(process.execPath, [cli, ...args], { cwd: dir, env: { PATH: process.env.PATH, ...env } });

  it("writes ha-types.d.ts with HA_URL and HA_TOKEN from the environment", async () => {
    const { stderr } = await typegen(["--out", "ha-types.d.ts"], {
      HA_URL: ha.url,
      HA_TOKEN: TOKEN,
    });
    expect(stderr).toMatch(/Wrote ha-types\.d\.ts: 1 entities, \d+ services/);
    expect(readFileSync(join(dir, "ha-types.d.ts"), "utf8")).toContain('"light.kitchen"');
  });

  it("prints to stdout with --url and --token", async () => {
    const { stdout } = await typegen(["--url", ha.url, "--token", TOKEN], {});
    expect(stdout).toMatch(/^\/\/ Generated by home-engine typegen/);
    expect(stdout).toContain('declare module "@home-engine/sdk"');
  });

  it("reads the token from HA_TOKEN_FILE", async () => {
    writeFileSync(join(dir, "token"), `${TOKEN}\n`);
    const { stdout } = await typegen([], { HA_URL: ha.url, HA_TOKEN_FILE: join(dir, "token") });
    expect(stdout).toContain('"light.kitchen"');
  });

  it("explains what is missing and exits 2 without URL and token", async () => {
    await expect(typegen([], {})).rejects.toMatchObject({
      code: 2,
      stderr: expect.stringMatching(/Set HA_URL and HA_TOKEN/),
    });
  });

  it("exits 1 with a clear message for a wrong token", async () => {
    await expect(typegen(["--url", ha.url, "--token", "wrong"], {})).rejects.toMatchObject({
      code: 1,
      stderr: expect.stringMatching(/rejected the access token/),
    });
  });
});
