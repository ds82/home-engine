import type { StartupTrigger, StateTrigger } from "@home-engine/sdk";
import { describe, expect, it } from "vitest";
import {
  FileEvaluationError,
  RegistrationError,
  evaluateFile,
  registerSetupRule,
  registerTriggeredRule,
} from "./registration.js";

const motion: StateTrigger = { kind: "state", entities: ["binary_sensor.motion"] };
const startup: StartupTrigger = { kind: "startup" };
const noop = (): void => {};

describe("rule registration", () => {
  it("registers several rules from one file with IDs <path>#<name>", async () => {
    const rules = await evaluateFile("lights.ts", async () => {
      registerTriggeredRule("hallway motion", motion, noop);
      registerTriggeredRule("porch at sunset", [startup, motion], noop, { mode: "restart" });
    });
    expect(rules.map((r) => r.id)).toEqual(["lights#hallway motion", "lights#porch at sunset"]);
    expect(rules[1]).toMatchObject({
      kind: "triggered",
      options: { mode: "restart" },
      file: "lights.ts",
    });
  });

  it("registers rules generated by a factory", async () => {
    const rules = await evaluateFile("presence.ts", async () => {
      const notifyOnArrival = (person: string): void =>
        registerTriggeredRule(`presence-${person}`, motion, noop);
      for (const person of ["dennis", "lydia"]) {
        notifyOnArrival(person);
      }
    });
    expect(rules.map((r) => r.id)).toEqual(["presence#presence-dennis", "presence#presence-lydia"]);
  });

  it("derives IDs of nested files and accepts explicit IDs", async () => {
    const rules = await evaluateFile("lights/hallway.mts", async () => {
      registerTriggeredRule("motion", motion, noop);
      registerSetupRule("counter", noop, { id: "kitchen-counter" });
    });
    expect(rules.map((r) => r.id)).toEqual(["lights/hallway#motion", "kitchen-counter"]);
    expect(rules[1]?.kind).toBe("setup");
  });

  it("registers nothing when the file throws after registering", async () => {
    const err = await evaluateFile("broken.ts", async () => {
      registerTriggeredRule("a", motion, noop);
      registerTriggeredRule("b", motion, noop);
      throw new Error("top-level failure");
    }).catch((e: unknown) => e);
    expect(err).toBeInstanceOf(FileEvaluationError);
    expect(err).toMatchObject({
      file: "broken.ts",
      message: expect.stringContaining("top-level failure"),
    });
    expect((err as Error).cause).toBeInstanceOf(Error);
  });

  it("rejects registration from a callback after the file was loaded", async () => {
    let later: (() => void) | undefined;
    const rules = await evaluateFile("callback.ts", async () => {
      later = () => registerTriggeredRule("late", motion, noop);
    });
    expect(rules).toEqual([]);
    expect(() => later?.()).toThrow(/can only be called while its rule file is loaded/);
    expect(() => registerSetupRule("outside", noop)).toThrow(RegistrationError);
  });

  it("includes rules registered after a top-level await", async () => {
    const rules = await evaluateFile("tla.ts", async () => {
      registerTriggeredRule("before", motion, noop);
      await new Promise((r) => setTimeout(r, 10));
      registerTriggeredRule("after", motion, noop);
    });
    expect(rules.map((r) => r.name)).toEqual(["before", "after"]);
  });

  it("fails a file whose evaluation does not settle in time, and rejects its late registrations", async () => {
    let lateError: unknown;
    const err = await evaluateFile(
      "slow.ts",
      async () => {
        registerTriggeredRule("early", motion, noop);
        await new Promise((r) => setTimeout(r, 100));
        try {
          registerTriggeredRule("late", motion, noop);
        } catch (e) {
          lateError = e;
        }
      },
      { timeoutMs: 20 },
    ).catch((e: unknown) => e);
    expect(err).toBeInstanceOf(FileEvaluationError);
    expect((err as Error).message).toMatch(/did not finish within/);
    await new Promise((r) => setTimeout(r, 120));
    expect(lateError).toBeInstanceOf(RegistrationError);
  });

  it("evaluates files one at a time", async () => {
    let release: () => void = () => {};
    const first = evaluateFile("a.ts", () => new Promise<void>((r) => (release = r)));
    await expect(evaluateFile("b.ts", async () => {})).rejects.toThrow(/one at a time/);
    release();
    await expect(first).resolves.toEqual([]);
    await expect(evaluateFile("b.ts", async () => {})).resolves.toEqual([]);
  });

  it("keeps the first rule of a duplicate name and throws for the second, across both kinds", async () => {
    let duplicate: unknown;
    const rules = await evaluateFile("dup.ts", async () => {
      registerTriggeredRule("motion", motion, noop);
      try {
        registerSetupRule("motion", noop);
      } catch (e) {
        duplicate = e;
      }
    });
    expect(rules.map((r) => r.kind)).toEqual(["triggered"]);
    expect(duplicate).toBeInstanceOf(RegistrationError);
    expect((duplicate as Error).message).toMatch(/Duplicate rule name "motion" in dup\.ts/);
  });

  it("fails the file when a duplicate name is not caught", async () => {
    await expect(
      evaluateFile("dup2.ts", async () => {
        registerTriggeredRule("motion", motion, noop);
        registerTriggeredRule("motion", motion, noop);
      }),
    ).rejects.toThrow(/Duplicate rule name "motion"/);
  });

  it("rejects a concurrency mode on setup rules", async () => {
    await expect(
      evaluateFile("setup.ts", async () => {
        registerSetupRule("counter", noop, { mode: "single" } as never);
      }),
    ).rejects.toThrow(/concurrency modes apply only to triggered rules/);
  });

  it.each([
    ["an empty name", () => registerTriggeredRule(" ", motion, noop), /non-empty/],
    [
      "an ID with #",
      () => registerTriggeredRule("x", motion, noop, { id: "a#b" }),
      /must not contain "#"/,
    ],
    ["no triggers", () => registerTriggeredRule("x", [], noop), /at least one trigger/],
    [
      "a non-function body",
      () => registerTriggeredRule("x", motion, "nope" as never),
      /must be a function/,
    ],
  ])("rejects %s", async (_label, register, message) => {
    await expect(evaluateFile("bad.ts", async () => register())).rejects.toThrow(message);
  });
});
